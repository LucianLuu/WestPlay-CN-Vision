import type { MapLabel } from '../maps/mapData'

/**
 * The place names the Dashboard shows in the cabin's language: the map's own names are in the language the
 * map was built with (Paris, Valladolid, Kraków), and the game's own job data names companies as its
 * definitions do (Transportes Caballería). Both are proper nouns, so this is a small dictionary rather than a
 * translation engine: the cities' names come from the map itself (`localized`, when the map has them), and
 * the companies' from below, with the game's name kept when it has none.
 */

/** A name as written for comparing: case, accents and surrounding spaces aside (`Kraków` = `Krakow`). */
export function plainName(name: string): string {
  return name
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLocaleLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * A city's name in the player's language: the map's `localized` name when it has one (the map is built from
 * the game's own text), else its own. `name` may be the game's job-data name, which matches the map's own.
 */
export function cityName(name: string, labels: readonly MapLabel[]): string {
  const wanted = plainName(name)
  if (!wanted) return name
  for (const label of labels) {
    if (label.kind !== 'city') continue
    if (plainName(label.name) === wanted || (label.localized !== undefined && plainName(label.localized) === wanted)) {
      return label.localized || label.name
    }
  }
  return name
}

